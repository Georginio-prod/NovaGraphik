-- ----------------------------------------------------------------------------
-- Row Level Security
-- ----------------------------------------------------------------------------
-- Helper note: auth.role() = 'authenticated' for any logged-in Supabase user.

-- Content tables with a `visible` flag: public reads visible rows, admins read all.
do $$
declare t text;
begin
  foreach t in array array[
    'sections','team_members','portfolio_items','nav_items','services',
    'articles','partners','testimonials','pricing_items','pricing_formulas'
  ]
  loop
    execute format('alter table public.%I enable row level security;', t);

    execute format('drop policy if exists %I on public.%I;', t||'_read', t);
    execute format($f$
      create policy %I on public.%I for select
      using (visible = 1 or auth.role() = 'authenticated');
    $f$, t||'_read', t);

    execute format('drop policy if exists %I on public.%I;', t||'_write', t);
    execute format($f$
      create policy %I on public.%I for all
      using (auth.role() = 'authenticated')
      with check (auth.role() = 'authenticated');
    $f$, t||'_write', t);
  end loop;
end $$;

-- settings: fully public to read (site config), authenticated to write.
alter table public.settings enable row level security;
drop policy if exists settings_read on public.settings;
create policy settings_read on public.settings for select using (true);
drop policy if exists settings_write on public.settings;
create policy settings_write on public.settings for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- ----------------------------------------------------------------------------
-- Storage: a single public `media` bucket for images & videos
-- ----------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do update set public = true;

drop policy if exists media_public_read on storage.objects;
create policy media_public_read on storage.objects for select
  using (bucket_id = 'media');

drop policy if exists media_auth_write on storage.objects;
create policy media_auth_write on storage.objects for all
  using (bucket_id = 'media' and auth.role() = 'authenticated')
  with check (bucket_id = 'media' and auth.role() = 'authenticated');
