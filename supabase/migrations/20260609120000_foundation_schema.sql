-- ============================================================================
-- Nova Graphik — Supabase schema (Postgres + RLS + Storage)
-- ============================================================================
-- Run this once in the Supabase SQL editor (or via the CLI) on the project
-- whose URL/anon key the frontend already uses for auth.
--
-- Authorization model (per the brief): a single shared admin login. Therefore:
--   • anon (public visitors) can READ only rows marked visible = 1
--   • any authenticated user can READ everything and WRITE (insert/update/delete)
--   • settings are fully public to read (site config), authenticated to write
-- This mirrors exactly what the old Express + requireAdmin backend enforced.
-- ============================================================================

